const LANG_KEY = 'asset-intake.lang';
let LANG = 'en';
try { LANG = localStorage.getItem(LANG_KEY) || 'en'; } catch {}
if (!I18N[LANG]) LANG = 'en';

/* t('key') or t('key', {n: 3}). Falls back to English, then to the key itself,
   so a missing translation is visible rather than silently blank. */
function t(key, vars) {
  let s = I18N[LANG][key];
  if (s == null) s = I18N.en[key];
  if (s == null) return key;
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

/* Apply to static markup:
     data-i18n       -> textContent
     data-i18n-html  -> innerHTML   (for strings carrying <b>/<code>)
     data-i18n-ph    -> placeholder
     data-i18n-title -> title (tooltip)                                 */
function applyI18n(root) {
  root = root || document;
  root.querySelectorAll('[data-i18n]').forEach(n => { n.textContent = t(n.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach(n => { n.innerHTML = t(n.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-ph]').forEach(n => { n.placeholder = t(n.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach(n => { n.title = t(n.dataset.i18nTitle); });
  document.documentElement.lang = LANG;
}

function setLang(l) {
  if (!I18N[l] || l === LANG) return false;
  LANG = l;
  try { localStorage.setItem(LANG_KEY, l); } catch {}
  return true;
}
